CREATE TABLE IF NOT EXISTS Cliente (
    id VARCHAR(50) PRIMARY KEY NOT NULL,
    nombre VARCHAR(50) NOT NULL,
    apellido VARCHAR(50) NOT NULL,
    direccion VARCHAR(100) NOT NULL,
    cedula VARCHAR(15) NOT NULL UNIQUE,
    urlImg VARCHAR(200)
);
CREATE TABLE IF NOT EXISTS Persona (
    id VARCHAR(50) PRIMARY KEY NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    contrasenha VARCHAR(255) NOT NULL,
    estado VARCHAR(2) NOT NULL,
    clienteId VARCHAR(50) NOT NULL REFERENCES Cliente(id)
);
CREATE TABLE IF NOT EXISTS Categoria (
    id VARCHAR(50) PRIMARY KEY NOT NULL,
    nombre VARCHAR(50) NOT NULL
);
CREATE TABLE IF NOT EXISTS Producto (
    id VARCHAR(50) PRIMARY KEY NOT NULL,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(50) NOT NULL,
    marca VARCHAR(50) NOT NULL,
    serie VARCHAR(50) NOT NULL,
    stock BIGINT NOT NULL,
    precioActual DOUBLE NOT NULL,
    fechaVencimiento TIMESTAMP NOT NULL,
    urlImg VARCHAR(200),
    idCategoria VARCHAR(50) NOT NULL REFERENCES Categoria(id)
);
CREATE TABLE IF NOT EXISTS Venta (
    id VARCHAR(50) PRIMARY KEY NOT NULL,
    fechaVenta TIMESTAMP NOT NULL,
    totalVenta DOUBLE NOT NULL,
    metodoPago VARCHAR(10) NOT NULL CHECK (metodoPago IN ('TARJETA', 'PSE', 'EFECTY')),
    idCliente VARCHAR(50) NOT NULL REFERENCES Cliente(id)
);
CREATE TABLE IF NOT EXISTS DetalleVenta (
    id VARCHAR(50) PRIMARY KEY NOT NULL,
    cantidad BIGINT NOT NULL,
    subtotal DOUBLE NOT NULL,
    precioVenta DOUBLE NOT NULL,
    idProducto VARCHAR(50) NOT NULL REFERENCES Producto(id),
    idVenta VARCHAR(50) NOT NULL REFERENCES Venta(id)
);
CREATE TABLE IF NOT EXISTS Promocion (
    id VARCHAR(50) PRIMARY KEY NOT NULL,
    nombre VARCHAR(50) NOT NULL,
    descuento DOUBLE NOT NULL,
    fechaInicio TIMESTAMP,
    fechaFin TIMESTAMP,
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('GENERAL', 'ESPECIFICA'))
);
CREATE TABLE IF NOT EXISTS PromocionCliente (
    id VARCHAR(50) PRIMARY KEY NOT NULL,
    idPromocion VARCHAR(50) NOT NULL REFERENCES Promocion(id),
    idCliente VARCHAR(50) NOT NULL REFERENCES Cliente(id)
);
CREATE TABLE IF NOT EXISTS PromocionProducto (
    id VARCHAR(50) PRIMARY KEY NOT NULL,
    idPromocion VARCHAR(50) NOT NULL REFERENCES Promocion(id),
    idProducto VARCHAR(50) NOT NULL REFERENCES Producto(id)
);
CREATE TABLE IF NOT EXISTS ColaSincronizadora (
    secuencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id VARCHAR(50) NOT NULL UNIQUE,
    accion VARCHAR(6) NOT NULL CHECK (accion IN ('INSERT', 'UPDATE', 'DELETE')),
    tablaAfectada VARCHAR(50) NOT NULL,
    idRegistroAfectado VARCHAR(50) NOT NULL,
    registroJson CLOB NOT NULL,
    estado VARCHAR(2) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_estado ON ColaSincronizadora(estado);
